# Purpose:
#   Apply remaining inclusion/exclusion criteria and
#   produce the analytical cohort and cohort flow summary.
#
# Criteria already applied in 01_dataset_definition.py:
#   - Registered death in ONS within the study period
#   - Age 0-110 years, including infants aged <1 year
#   - Exclusion of missing/unknown sex
#
# Criteria applied in this script:
#   - Exclude deaths before the month of birth
#   - Exclude individuals not registered with a TPP
#     practice on the day before death
#
# The cohort flow summarises sequential exclusions
# from the extracted dataset to the final analytical cohort.
####################################################


library(dplyr)
library(readr)

# -----------------------------------------------------------------------------
# Import utilities
# -----------------------------------------------------------------------------

source("analysis/00_utilities.R")


# -----------------------------------------------------------------------------
# Set parameters
# -----------------------------------------------------------------------------

# Set Prefix for all output files generated by this script.
# This should match the script number (e.g. "01", "02", "03")
script_prefix <- "02"


# -----------------------------------------------------------------------------
# Read data
# -----------------------------------------------------------------------------
# Read extracted OpenSAFELY dataset (dummy or real)
death_data <- read_csv(
  "output/highly_sensitive/dataset_death_ons_tpp.csv.gz"
)

# =============================================================================
# Apply study inclusion and exclusion criteria
# =============================================================================

# Flag records with valid date sequences
death_data <- death_data %>%
  mutate(
    ons_death_date = as.Date(ons_death_date),
    date_of_birth = as.Date(date_of_birth),

    # Allow deaths in the same month as birth due to limited DOB precision
    valid_date_sequence =
      !is.na(date_of_birth) &
      !is.na(ons_death_date) &
      (
        ons_death_date >= date_of_birth |
          format(ons_death_date, "%Y-%m") ==
            format(date_of_birth, "%Y-%m")
      )
  )


# ---------------
# Step 1: Exclude records with impossible date sequences
valid_date_sequence_data <- death_data %>%
  filter(valid_date_sequence)

impossible_date_sequence <- death_data %>%
  filter(!valid_date_sequence)


# ---------------
# Step 2: Include only those registered on the day before death
analysis_cohort <- valid_date_sequence_data %>%
  filter(registered_day_before_death %in% TRUE)

not_registered_day_before_death <- valid_date_sequence_data %>%
  filter(!(registered_day_before_death %in% TRUE))


# -----------------------------------------------------------------------------
# Cohort flow summary
# -----------------------------------------------------------------------------

cohort_flow <- tibble(
  step = c(
    "Total records extracted",
    "Excluded: death before month of birth or missing date of birth",
    "Excluded: not registered with TPP on day before death",
    "Final analytical cohort"
  ),
  n = c(
    nrow(death_data),
    nrow(impossible_date_sequence),
    nrow(not_registered_day_before_death),
    nrow(analysis_cohort)
  )
)


# -----------------------------------------------------------------------------
# Apply disclosure control
# -----------------------------------------------------------------------------

# Apply SDC and format redacted counts for output
cohort_flow <- cohort_flow %>%
  mutate(
    n = apply_sdc(n),
    n = if_else(
      is.na(n),
      "[REDACTED]",
      as.character(n)
    )
  )


# -----------------------------------------------------------------------------
# Save outputs
# -----------------------------------------------------------------------------

# Save disclosure-controlled cohort flow
write_csv(
  cohort_flow,
  paste0("output/", script_prefix, "_cohort_flow.csv")
)

# Save final analytical cohort
write_csv(
  analysis_cohort,
  paste0("output/", script_prefix, "_cohort.csv")
)